#!/usr/bin/env python3
"""Draw the telemetry card from live GitHub data (standard library only).

Usage: stats.py OUTPUT.svg            (needs GITHUB_TOKEN and GITHUB_USER)
       stats.py OUTPUT.svg --preview  (no data, shows placeholders)
"""
import datetime
import json
import os
import sys
import urllib.request
from pathlib import Path

GLYPHS = json.loads((Path(__file__).parent / "glyphs.json").read_text())
CYAN, BLUE, PURPLE, GREEN = "#22e4ff", "#3d7bff", "#9d6bff", "#3ee6a4"
QUERY = """query($login: String!) {
  user(login: $login) {
    repositories(ownerAffiliations: OWNER, privacy: PUBLIC, isFork: false) { totalCount }
    contributionsCollection { contributionCalendar {
      totalContributions
      weeks { contributionDays { date contributionCount } }
    } }
  }
}"""


def fetch(login, token):
    req = urllib.request.Request(
        "https://api.github.com/graphql",
        data=json.dumps({"query": QUERY, "variables": {"login": login}}).encode(),
        headers={"Authorization": f"bearer {token}", "User-Agent": "profile-stats"})
    with urllib.request.urlopen(req, timeout=30) as res:
        body = json.load(res)
    if body.get("errors") or not body.get("data", {}).get("user"):
        raise SystemExit(f"GitHub API error: {body.get('errors', body)}")
    return body["data"]["user"]


def summarise(user):
    cal = user["contributionsCollection"]["contributionCalendar"]
    weeks = [[d["contributionCount"] for d in w["contributionDays"]] for w in cal["weeks"]]
    longest = run = 0
    for count in (c for w in weeks for c in w):
        run = run + 1 if count else 0
        longest = max(longest, run)
    return {"tiles": [cal["totalContributions"], sum(1 for w in weeks for c in w if c),
                      longest, user["repositories"]["totalCount"]],
            "weeks": [sum(w) for w in weeks]}


def text(x, y, value, size, face, fill, anchor="start"):
    font = GLYPHS[face]
    k = size / font["upm"]
    glyphs = [font["glyphs"][c] for c in value]
    total = sum(g["w"] for g in glyphs) * k
    x -= {"start": 0, "middle": total / 2, "end": total}[anchor]
    out, cx = [], 0
    for g in glyphs:
        out.append(f'<path transform="translate({cx} 0)" d="{g["d"]}"/>')
        cx += g["w"]
    return f'<g transform="translate({x:.1f} {y}) scale({k:.5f} {-k:.5f})" fill="{fill}">{"".join(out)}</g>'


def draw(data, stamp):
    body = ['<rect x=".75" y=".75" width="898.5" height="268.5" rx="18" fill="#0a1327" stroke="#1c2d52" stroke-width="1.5"/>']
    labels = ["CONTRIBUTIONS", "ACTIVE DAYS", "LONGEST STREAK", "PUBLIC REPOS"]
    for i, (label, colour) in enumerate(zip(labels, (CYAN, BLUE, PURPLE, GREEN))):
        x = 22 + i * 217
        value = "--" if data is None else str(data["tiles"][i])
        body.append(f'<rect x="{x}" y="20" width="205" height="94" rx="12" fill="#050a17" stroke="{colour}" stroke-opacity=".4"/>')
        body.append(text(x + 18, 71, value, 36, "black", "#eef5ff"))
        body.append(text(x + 18, 96, label, 11, "monob", colour))
    body.append(text(22, 142, "WEEKLY ACTIVITY  /  LAST 12 MONTHS", 11, "monob", "#7f94bb"))
    weeks = [0] * 53 if data is None else data["weeks"][-53:]
    peak = max(weeks) or 1
    step = 856 / len(weeks)
    for i, count in enumerate(weeks):
        h = max(3, 82 * count / peak)
        colour = "#1c2d52" if not count else CYAN if i > len(weeks) * .66 else BLUE if i > len(weeks) * .33 else PURPLE
        body.append(f'<rect class="b" style="animation-delay:{i * .02:.2f}s" x="{22 + i * step:.1f}" y="{236 - h:.1f}" '
                    f'width="{step - 4:.1f}" height="{h:.1f}" rx="2" fill="{colour}"/>')
    body.append(text(878, 142, stamp, 11, "mono", "#7f94bb", "end"))
    body.append(text(450, 256, "generated by a GitHub Action in this repository", 10, "mono", "#7f94bb", "middle"))
    css = ("@keyframes grow{from{transform:scaleY(.05)}}.b{transform-box:fill-box;transform-origin:bottom;"
           "animation:grow 1s ease-out both}@media (prefers-reduced-motion:reduce){.b{animation:none}}")
    summary = "GitHub activity" if data is None else (
        f"GitHub activity: {data['tiles'][0]} contributions, {data['tiles'][1]} active days, "
        f"longest streak {data['tiles'][2]} days, {data['tiles'][3]} public repositories")
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="900" height="270" viewBox="0 0 900 270" role="img" aria-label="{summary}">'
            f'<title>{summary}</title><style>{css}</style>{"".join(body)}</svg>')


def main():
    out = Path(sys.argv[1])
    if "--preview" in sys.argv:
        data, stamp = None, "values appear after the first run"
    else:
        data = summarise(fetch(os.environ["GITHUB_USER"], os.environ["GITHUB_TOKEN"]))
        stamp = f"updated {datetime.date.today().isoformat()}"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(draw(data, stamp))


if __name__ == "__main__":
    main()
